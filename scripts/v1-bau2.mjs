import { chromium } from "playwright";
const b = await chromium.launch();
let p = await b.newPage({ viewport: { width: 1440, height: 900 } });
await p.goto("http://localhost:5188", { waitUntil: "load" });
await p.click(".thema-knopf");
const oben = await p.evaluate(() => document.querySelector("#bau").getBoundingClientRect().top + scrollY);
await p.evaluate((y) => window.scrollTo(0, y + 3000), oben);
await p.waitForTimeout(2500);
await p.screenshot({ path: "ansichten/bau-dunkel-ende.png" });
await p.close();
p = await b.newPage({ viewport: { width: 375, height: 800 }, isMobile: true, hasTouch: true });
